#!/usr/bin/env node
/**
 * Build the publishable dist/ folder.
 *
 * The library has no runtime or build dependency: zidan-form.js is already a
 * UMD-compatible classic script and zidan-form.mjs is its ESM wrapper. This
 * script assembles dist/, writes the select-only and file-only bundles by
 * slicing @zidan-build sections, and — if esbuild happens to be installed —
 * writes minified copies. Nothing is required for the repo to work.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const assets = ['zidan-form.js', 'zidan-form.mjs', 'plugin-core.css', 'plugin-theme.css'];

const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version;

const MARKER = /\/\* @zidan-build:([a-z0-9-]+) \*\/[ \t]*\r?\n?/g;

function splitSections(text, label) {
  const sections = [];
  let last = 0;
  let name = 'head';
  let match;
  MARKER.lastIndex = 0;
  while ((match = MARKER.exec(text))) {
    sections.push({ name, body: text.slice(last, match.index) });
    name = match[1];
    last = MARKER.lastIndex;
  }
  sections.push({ name, body: text.slice(last) });
  if (!sections.some((section) => section.name === 'head')) {
    throw new Error(label + ': no leading section found');
  }
  return sections;
}

function take(sections, names, label) {
  const missing = names.filter((name) => !sections.some((section) => section.name === name));
  if (missing.length) {
    throw new Error(label + ': missing build sections: ' + missing.join(', '));
  }
  return sections
    .filter((section) => names.includes(section.name))
    .map((section) => section.body)
    .join('');
}

function replaceBanner(text, banner) {
  return text.replace(/^\/\*![\s\S]*?\*\//, banner.trim());
}

const source = await fs.readFile(path.join(root, 'zidan-form.js'), 'utf8');
const coreCss = await fs.readFile(path.join(root, 'plugin-core.css'), 'utf8');
const themeCss = await fs.readFile(path.join(root, 'plugin-theme.css'), 'utf8');

const jsSections = splitSections(source, 'zidan-form.js');
const coreSections = splitSections(coreCss, 'plugin-core.css');
const themeSections = splitSections(themeCss, 'plugin-theme.css');

const repo = 'https://github.com/akhtar1985/zidan-select';

function jsBanner(name, description, pairing, globalLine) {
  return `/*!
 * ZidanForm ${name} v${version}
 * ${description}
 * ${pairing}
 *
 * Generated by scripts/build.mjs — edit zidan-form.js instead.
 * ${repo}
 * MIT License © akhtar1985
 *
 * ${globalLine}
 */
`;
}

function cssBanner(name, kind, description, pairing) {
  return `/*!
 * ZidanForm ${name} v${version} — ${kind}
 * ${description}
 * ${pairing}
 *
 * Generated by scripts/build.mjs — edit the shared stylesheets instead.
 * ${repo}
 * MIT License © akhtar1985
 */
`;
}

const jsHead = jsSections.find((section) => section.name === 'head').body;

const variants = [
  {
    dir: 'select',
    js: 'zidan-select.js',
    mjs: 'zidan-select.mjs',
    dts: 'zidan-select.d.ts',
    core: 'plugin-select-core.css',
    theme: 'plugin-select-theme.css',
    jsSections: ['shared', 'shared2', 'select-defaults', 'select', 'factory'],
    coreSections: ['scope', 'select-shell', 'select-values', 'select-dropdown', 'select-layouts', 'form-layout', 'focus'],
    themeSections: ['tokens', 'select-paint', 'select-layouts', 'scrollbar', 'preset-themes', 'adapters', 'forced'],
    jsHead: jsBanner(
      'Select-only',
      'Zero-dependency select / combobox / tags enhancement. Every other control family is omitted.',
      'Pairs with plugin-select-core.css and plugin-select-theme.css.',
      'Classic <script> adds window.ZidanForm plus window.ZidanSelect / zidanSelect / initZidanSelects.'
    ),
    coreHead: cssBanner(
      'Select-only',
      'plugin-select-core.css',
      'Structure for the select / combobox / tags control only.',
      'Pairs with zidan-select.js and plugin-select-theme.css.'
    ),
    themeHead: cssBanner(
      'Select-only',
      'plugin-select-theme.css',
      'Tokens, 5 preset themes, select layouts, scrollbars and framework adapters.',
      'Pairs with zidan-select.js and plugin-select-core.css.'
    ),
    mjsSource: `/**
 * ZidanForm Select-only — ES module entry point.
 *
 *   import { ZidanSelect, zidanSelect } from './zidan-select.mjs';
 *
 * Pairs with plugin-select-core.css and plugin-select-theme.css.
 * ${repo}
 */
import './zidan-select.js';

const host = typeof window !== 'undefined' ? window : globalThis;

if (!host.ZidanForm) {
  throw new Error('ZidanForm: subset script did not initialise (no DOM available?).');
}

const core = host.ZidanForm.api || host;

export const ZidanForm = host.ZidanForm;
export const ZidanSelect = core.ZidanSelect;
export const zidanSelect = core.zidanSelect;
export const initZidanSelects = core.initZidanSelects;
export const registerIcon = core.registerIcon;
export default ZidanForm;
`,
    typesSource: `/**
 * ZidanForm Select-only v${version} — type definitions.
 * ${repo}
 */
export {
  ZidanForm,
  ZidanSelect,
  zidanSelect,
  initZidanSelects,
  registerIcon
} from '../../zidan-form';
export type {
  SelectMode,
  SelectLayout,
  Framework,
  Theme,
  Scrollbar,
  ValidationState,
  SelectItem,
  SelectGroup,
  SelectItemInput,
  FetchContext,
  FetchPage,
  FetchResult,
  FetchOptions,
  SelectCallbacks,
  SelectOptions,
  SelectAsyncState,
  ZidanFormStatic,
  AutoInitTarget,
  AutoInitConfig
} from '../../zidan-form';
export { default } from '../../zidan-form';
`
  },
  {
    dir: 'file',
    js: 'zidan-file.js',
    mjs: 'zidan-file.mjs',
    dts: 'zidan-file.d.ts',
    core: 'plugin-file-core.css',
    theme: 'plugin-file-theme.css',
    jsSections: ['shared', 'shared2', 'fields', 'file', 'factory'],
    coreSections: ['scope', 'fields-shared', 'file', 'form-layout', 'focus'],
    themeSections: ['tokens', 'field-paint', 'preset-themes', 'field-layout-paint', 'adapters', 'file-adapters', 'forced'],
    jsHead: jsBanner(
      'File-only',
      'Zero-dependency drag & drop file upload with variants, previews, limits and progress.',
      'Pairs with plugin-file-core.css and plugin-file-theme.css.',
      'Classic <script> adds window.ZidanForm plus window.zidanField / initZidanForms.'
    ),
    coreHead: cssBanner(
      'File-only',
      'plugin-file-core.css',
      'Structure for the file upload control only.',
      'Pairs with zidan-file.js and plugin-file-theme.css.'
    ),
    themeHead: cssBanner(
      'File-only',
      'plugin-file-theme.css',
      'Tokens, 5 preset themes, field layouts and framework adapters.',
      'Pairs with zidan-file.js and plugin-file-core.css.'
    ),
    mjsSource: `/**
 * ZidanForm File-only — ES module entry point.
 *
 *   import { ZidanFileUpload, zidanField } from './zidan-file.mjs';
 *
 * Pairs with plugin-file-core.css and plugin-file-theme.css.
 * ${repo}
 */
import './zidan-file.js';

const host = typeof window !== 'undefined' ? window : globalThis;

if (!host.ZidanForm) {
  throw new Error('ZidanForm: subset script did not initialise (no DOM available?).');
}

const core = host.ZidanForm.api || host;

export const ZidanForm = host.ZidanForm;
export const ZidanFileUpload = core.ZidanFileUpload;
export const zidanField = core.zidanField;
export const initZidanForms = core.initZidanForms;
export const registerIcon = core.registerIcon;
export default ZidanForm;
`,
    typesSource: `/**
 * ZidanForm File-only v${version} — type definitions.
 * ${repo}
 */
export {
  ZidanForm,
  ZidanFileUpload,
  ZidanFieldBase,
  zidanField,
  initZidanForms,
  registerIcon
} from '../../zidan-form';
export type {
  Framework,
  Theme,
  FieldLayout,
  ValidationState,
  AsyncValidationContext,
  AsyncRuleResult,
  RuleResult,
  FieldRule,
  FieldMessages,
  FieldOptions,
  FileFieldOptions,
  UploadContext,
  UploadHandler,
  UploadState,
  ZidanFormStatic,
  AutoInitTarget,
  AutoInitConfig
} from '../../zidan-form';
export { default } from '../../zidan-form';
`
  }
];

await fs.rm(dist, { recursive: true, force: true });
await fs.mkdir(dist, { recursive: true });

for (const asset of assets) {
  await fs.copyFile(path.join(root, asset), path.join(dist, asset));
}

await fs.writeFile(
  path.join(dist, 'zidan-form.cjs'),
  "'use strict';\nmodule.exports = require('../zidan-form.js');\n",
  'utf8'
);

for (const variant of variants) {
  const dir = path.join(dist, variant.dir);
  await fs.mkdir(dir, { recursive: true });

  const script = replaceBanner(jsHead, variant.jsHead) +
    take(jsSections, variant.jsSections, variant.js);
  const core = replaceBanner(
    coreSections.find((section) => section.name === 'head').body,
    variant.coreHead
  ) + take(coreSections, variant.coreSections, variant.core);
  const theme = replaceBanner(
    themeSections.find((section) => section.name === 'head').body,
    variant.themeHead
  ) + take(themeSections, variant.themeSections, variant.theme);

  const jsPath = path.join(dir, variant.js);
  await fs.writeFile(jsPath, script, 'utf8');
  await fs.writeFile(path.join(dir, variant.mjs), variant.mjsSource, 'utf8');
  await fs.writeFile(path.join(dir, variant.dts), variant.typesSource, 'utf8');
  await fs.writeFile(path.join(dir, variant.core), core, 'utf8');
  await fs.writeFile(path.join(dir, variant.theme), theme, 'utf8');

  execFileSync(process.execPath, ['--check', jsPath], { stdio: 'pipe' });
}

let minified = false;
try {
  const esbuild = await import('esbuild');
  await esbuild.build({
    entryPoints: [path.join(root, 'zidan-form.js')],
    outfile: path.join(dist, 'zidan-form.min.js'),
    bundle: false,
    minify: true,
    target: ['es2019'],
    legalComments: 'inline',
    logLevel: 'silent'
  });
  for (const css of ['plugin-core.css', 'plugin-theme.css']) {
    await esbuild.build({
      entryPoints: [path.join(root, css)],
      outfile: path.join(dist, css.replace('.css', '.min.css')),
      minify: true,
      logLevel: 'silent'
    });
  }
  for (const variant of variants) {
    const dir = path.join(dist, variant.dir);
    await esbuild.build({
      entryPoints: [path.join(dir, variant.js)],
      outfile: path.join(dir, variant.js.replace(/\.js$/, '.min.js')),
      bundle: false,
      minify: true,
      target: ['es2019'],
      legalComments: 'inline',
      logLevel: 'silent'
    });
    for (const css of [variant.core, variant.theme]) {
      await esbuild.build({
        entryPoints: [path.join(dir, css)],
        outfile: path.join(dir, css.replace(/\.css$/, '.min.css')),
        minify: true,
        logLevel: 'silent'
      });
    }
  }
  minified = true;
} catch (err) {
  if (err && err.code !== 'ERR_MODULE_NOT_FOUND') throw err;
}

console.log('built dist/ (' + assets.length + ' files + CJS entry)');
console.log('built subset bundles: select/ (5 files), file/ (5 files)');
console.log(minified ? 'minified copies written with esbuild (full + both subsets)' : 'esbuild not installed — skipped minified copies');
